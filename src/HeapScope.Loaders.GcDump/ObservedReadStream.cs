namespace HeapScope.Loaders.GcDump;

/// <summary>
/// A read-only view of a stream that checks a cancellation token on every read and reports the position at most every
/// <see cref="ReportInterval"/> bytes: a reader that takes a stream and runs to the end gets progress and cancellation.
/// </summary>
internal sealed class ObservedReadStream(Stream inner, Action<long> report, CancellationToken cancellationToken) : Stream
{
    public const long ReportInterval = 16L * 1024 * 1024;

    private long _nextReport;

    public override bool CanRead => true;

    public override bool CanSeek => inner.CanSeek;

    public override bool CanWrite => false;

    public override long Length => inner.Length;

    public override long Position
    {
        get => inner.Position;
        set => inner.Position = value;
    }

    public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));

    public override int Read(Span<byte> buffer)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var read = inner.Read(buffer);
        if (inner.Position >= _nextReport)
        {
            _nextReport = inner.Position + ReportInterval;
            report(inner.Position);
        }

        return read;
    }

    public override long Seek(long offset, SeekOrigin origin) => inner.Seek(offset, origin);

    public override void Flush()
    {
    }

    public override void SetLength(long value) => throw new NotSupportedException();

    public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
}
